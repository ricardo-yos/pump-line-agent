"""
pump_catalog.py

Pump catalog (KSB Etanorm line) used by the pump-line-agent.

Each entry represents a real combination of model + impeller diameter +
speed, with H(Q) and P(Q) curves fitted as polynomials from points
digitized off the manufacturer's published performance curves (these are
NOT curves derived via affinity laws).

Polynomial degree is NOT fixed across the catalog: real pump curves
deviate from the idealized parabolic (degree-2) shape from turbomachinery
theory, so different curves may fit best at different degrees (2, 3, or
4). Each curve stores its own "coef_H"/"coef_P"/"coef_NPSHr" list AND a
matching "*_degree" field - tools.py must read the degree, not assume a
fixed number of coefficients. Prefer the lowest degree that gives a good
fit (R2) over the highest R2 available, to avoid overfitting noise from
digitization - see fit_curve.py / batch_fit.py.

NPSHr curves are often published covering a RANGE of diameters (not one
per diameter) - so they live in a separate dict (NPSH_CURVES), and each
pump entry references its curve via "npsh_curve_id". When the impeller
diameter falls between the two extremes of the NPSH curve, NPSHr is
linearly interpolated between them (see pump_sizing.py). A shared curve
that applies to every diameter of a model (no interpolation) is stored
with "coef_NPSHr" and "diameter_range_mm": (0, 0) as a sentinel meaning
"diameter-independent" - see pump_sizing.evaluate_NPSHr.

Data attribution:
The coefficients below were derived from self-performed digitization
(points extracted manually / via WebPlotDigitizer) of performance curves
published in official KSB technical catalogs. Raw data (digitized points,
catalog images) is NOT versioned in this repository - only the resulting
coefficients, with source attribution on each entry. Catalog document:
1311.46/12-EN-US. Page numbers are TODO per entry - fill in from the PDF.
"""

