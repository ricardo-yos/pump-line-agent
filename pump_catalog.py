def get_pump(model_id: str) -> dict:
    """Returns pump data for a given catalog id."""
    if model_id not in PUMP_CATALOG:
        raise KeyError(f"Pump '{model_id}' not found in catalog.")
    return PUMP_CATALOG[model_id]


def get_npsh_curve(npsh_curve_id: str) -> dict:
    """Returns data for a shared NPSH curve."""
    if npsh_curve_id not in NPSH_CURVES:
        raise KeyError(f"NPSH curve '{npsh_curve_id}' not found.")
    return NPSH_CURVES[npsh_curve_id]


def list_pumps(Q_target: float | None = None) -> list[str]:
    """Lists pump ids; if Q_target is given, filters to only those covering
    that flow within Q_min_curve-Q_max_curve."""
    if Q_target is None:
        return list(PUMP_CATALOG.keys())
    return [
        pid for pid, p in PUMP_CATALOG.items()
        if p["Q_min_curve"] <= Q_target <= p["Q_max_curve"]
    ]
